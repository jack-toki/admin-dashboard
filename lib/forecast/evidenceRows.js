function minor(value) {
  return value == null ? null : Number(value);
}

function text(value) {
  return value == null ? null : value;
}

export function evidenceToRows(evidence) {
  return {
    accountingPeriods: evidence.accountingPeriods.map((row) => ({
      period: row.period,
      coverage: row.coverage,
      basis: row.basis || 'unknown',
      currency: row.currency || 'GBP',
      notes: text(row.notes),
    })),
    accountingLines: evidence.accountingLines.map((row) => ({
      id: row.id,
      period: row.period,
      account_label: row.accountLabel,
      group_id: text(row.groupId),
      source_workbook_id: row.sourceWorkbookId,
      source_sheet_id: row.sourceSheetId,
      source_cell: row.sourceCell,
      source_row: text(row.sourceRow),
      source_label: text(row.sourceLabel),
      role: row.role,
      amount_minor: text(row.amountMinor),
      exact_numeric: text(row.exactNumeric),
      source_cell_state: row.sourceCellState,
      coverage: row.coverage,
      cash_received_proven: row.cashReceivedProven === true,
      source_hash: row.sourceHash,
    })),
    alternativeCells: evidence.alternativeCells.map((row) => ({
      id: row.id,
      scenario_id: row.scenarioId,
      label: row.label,
      source_workbook_id: row.sourceWorkbookId,
      source_sheet_id: row.sourceSheetId,
      source_cell: row.sourceCell,
      source_row: row.sourceRow,
      period: text(row.period),
      role: row.role,
      amount_minor: text(row.amountMinor),
      exact_numeric: text(row.exactNumeric),
      cell_state: row.cellState,
      is_primary: false,
      is_actual: false,
      source_hash: row.sourceHash,
    })),
    reconciliation: evidence.reconciliation.map((row) => ({
      id: row.id,
      source_workbook_id: row.sourceWorkbookId,
      source_sheet_id: row.sourceSheetId,
      source_cell: row.sourceCell,
      source_row: text(row.sourceRow),
      source_label: text(row.sourceLabel),
      period: text(row.period),
      role: row.role,
      exact_numeric: text(row.exactNumeric),
      amount_minor: text(row.amountMinor),
      include_in_operational_sum: false,
      source_hash: row.sourceHash,
    })),
    invoices: evidence.invoices.map((row) => ({
      id: row.id,
      source_workbook_id: row.sourceWorkbookId,
      source_sheet_id: row.sourceSheetId,
      source_row: row.sourceRow,
      invoice_number: text(row.invoiceNumber),
      invoice_date: text(row.invoiceDate),
      due_date: text(row.dueDate),
      paid_minor: text(row.paidMinor),
      due_minor: text(row.dueMinor),
      source_status: text(row.sourceStatus),
      cash_claim: row.cashClaim,
      party_private: text(row.party),
      evidence_is_live_xero: false,
      source_hash: row.sourceHash,
    })),
    planning: evidence.planning.map((row) => ({
      id: row.id,
      source_workbook_id: row.sourceWorkbookId,
      source_sheet_id: row.sourceSheetId,
      source_cell: row.sourceCell,
      source_row: text(row.sourceRow),
      source_label: text(row.sourceLabel),
      plan_kind: row.planKind,
      period: text(row.period),
      party_private: text(row.party),
      amount_minor: text(row.amountMinor),
      exact_numeric: text(row.exactNumeric),
      probability_exact: text(row.probabilityExact),
      status: text(row.status),
      linked_primary_ref: text(row.linkedPrimaryRef),
      is_actual: false,
      adds_to_cost: false,
      source_hash: row.sourceHash,
    })),
  };
}

